import { expect, test } from './test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

test.use({ viewport: { height: 1080, width: 1920 } });

const EXAMPLES = join(process.cwd(), 'plugins', 'examples');

test('installs a plugin and its export format appears and downloads', async ({
  editPage,
  page
}) => {
  await page.getByTestId('plugin-manager-open').click();
  const manager = page.getByTestId('plugin-manager');
  await expect(manager).toBeVisible();

  const chooserPromise = page.waitForEvent('filechooser');
  await page.getByTestId('plugin-install').click();
  const chooser = await chooserPromise;
  await chooser.setFiles(join(EXAMPLES, 'mc-exporter.mjs'));
  await expect(manager.getByText('MC 函数导出（示例）')).toBeVisible({ timeout: 10_000 });

  // The plugin export format is appended to the 导出 menu.
  await page.getByTestId('plugin-manager').getByRole('button', { name: '关闭' }).click();
  await editPage.ensureActionsOpen();
  await page.getByTestId('export-menu').click();
  const item = page.getByTestId('plugin-export-mcfunction');
  await expect(item).toBeVisible();

  const dlPromise = page.waitForEvent('download');
  await item.click();
  const dl = await dlPromise;
  expect(dl.suggestedFilename()).toBe('diagram.mcfunction');
  const text = readFileSync((await dl.path()) as string, 'utf-8');
  expect(text).toContain('# Generated by flow-editor plugin demo.mc-exporter');
  expect(text).toContain('tellraw @a');
});

test('input transform plugin cleans an opened file', async ({ editPage, page }) => {
  await page.getByTestId('plugin-manager-open').click();
  const chooserPromise = page.waitForEvent('filechooser');
  await page.getByTestId('plugin-install').click();
  const chooser = await chooserPromise;
  await chooser.setFiles(join(EXAMPLES, 'input-cleaner.mjs'));
  await page.waitForTimeout(1500);
  await page.getByTestId('plugin-manager').getByRole('button', { name: '关闭' }).click();

  // A file with CRLF line endings, trailing spaces and a PlantUML wrapper:
  // the plugin must strip the wrapper and normalize on the way in.
  await editPage.ensureActionsOpen();
  const chooser2 = page.waitForEvent('filechooser');
  await page.getByTestId('open-file').click();
  const c2 = await chooser2;
  await c2.setFiles({
    buffer: Buffer.from('@startuml\r\nflowchart TD\r\n  A --> B   \r\n@enduml\r\n'),
    mimeType: 'text/plain',
    name: 'wrapped.mmd'
  });
  await expect(page.locator('.monaco-editor')).toContainText('flowchart TD', { timeout: 10_000 });
  await page.waitForTimeout(500);
  const code = await page.evaluate(() => window.__FLOW_EDITOR_STATE__?.().code ?? '');
  expect(code).toContain('flowchart TD');
  expect(code).not.toContain('@startuml');
  expect(code).not.toContain('\r');
});

test('MCP bridge drives the editor over postMessage', async ({ page }) => {
  await page.goto('/edit');
  await page.locator('#view').waitFor({ state: 'visible' });
  const result = await page.evaluate(async () => {
    const CH = 'flow-editor';
    const call = (method: string, params?: Record<string, unknown>) =>
      new Promise<unknown>((resolve) => {
        const id = Math.random().toString(36).slice(2);
        const onMsg = (e: MessageEvent) => {
          const d = e.data as { channel?: string; id?: string };
          if (d?.channel === CH && d.id === id && ('result' in d || 'error' in (d as object))) {
            window.removeEventListener('message', onMsg);
            resolve(e.data);
          }
        };
        window.addEventListener('message', onMsg);
        window.postMessage({ channel: CH, id, jsonrpc: '2.0', method, params }, '*');
      });
    const init = (await call('initialize')) as { result?: { serverInfo?: { name?: string } } };
    const tools = (await call('tools/list')) as {
      result?: { tools?: { name: string }[] };
    };
    const set = (await call('tools/call', {
      name: 'set_code',
      arguments: { code: 'pie\n  "Dogs" : 386' }
    })) as { result?: { content?: { text: string }[] } };
    // set_code runs through the async state gateway — poll until it lands.
    let code = '';
    for (let i = 0; i < 30; i++) {
      await new Promise((r) => setTimeout(r, 100));
      const got = (await call('tools/call', { name: 'get_code', arguments: {} })) as {
        result?: { content?: { text: string }[] };
      };
      code = got.result?.content?.[0]?.text ?? '';
      if (code.includes('Dogs')) {
        break;
      }
    }
    const png = (await call('tools/call', {
      name: 'export',
      arguments: { format: 'png-dataurl' }
    })) as { result?: { content?: { text: string }[] } };
    return {
      code,
      initName: init.result?.serverInfo?.name,
      pngText: png.result?.content?.[0]?.text ?? '',
      setOk: set.result?.content?.[0]?.text,
      toolNames: tools.result?.tools?.map((t) => t.name)
    };
  });
  expect(result.initName).toBe('flow-editor');
  // Regression: export(png-dataurl) used to return the SVG data URL.
  expect(result.pngText).toMatch(/^data:image\/png;base64,/);
  expect(result.toolNames).toContain('set_code');
  expect(result.setOk).toBe('ok');
  expect(result.code).toContain('Dogs');
  await expect(page.locator('#container')).toContainText('Dogs');
});

test('plugin frontend replaces the UI and drives the editor via the bridge', async ({
  editPage,
  page
}) => {
  // The fixture also gives this test its /edit navigation.
  await editPage.view.waitFor({ state: 'visible' });
  await page.getByTestId('plugin-manager-open').click();
  const chooserPromise = page.waitForEvent('filechooser');
  await page.getByTestId('plugin-install').click();
  const chooser = await chooserPromise;
  await chooser.setFiles(join(EXAMPLES, 'frontend-embed.mjs'));
  await page.getByTestId('plugin-card-demo.frontend-embed').waitFor({ timeout: 10_000 });

  // Open the plugin frontend — a full-screen iframe replaces the UI.
  await page.getByRole('button', { name: /打开 内嵌前端替换/ }).click();
  const frame = page.frameLocator('iframe[title="插件前端"]');
  await expect(page.getByTestId('plugin-frontend-exit')).toBeVisible();
  // The embedded page auto-loads the editor code on mount.
  await expect(frame.locator('#code')).toHaveValue(/flowchart TD/, { timeout: 10_000 });

  // Write back through the bridge and verify the editor actually changed.
  const edited = 'pie\n  "Dogs" : 386\n  "Cats" : 85\n';
  await frame.locator('#code').fill(edited);
  await frame.getByRole('button', { name: '写回编辑器' }).click();
  await expect
    .poll(() => page.evaluate(() => window.__FLOW_EDITOR_STATE__?.().code ?? ''))
    .toContain('Dogs');

  // Exit restores the regular UI.
  await page.getByTestId('plugin-frontend-exit').click();
  await expect(page.locator('iframe[title="插件前端"]')).toHaveCount(0);
  await expect(page.locator('.monaco-editor')).toBeVisible();
});
